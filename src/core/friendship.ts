/**
 * ДРУЖБА И ЕЖЕЧАСНЫЙ СУНДУК.
 *
 * Дружба даёт смысл выбору главного друга: раньше он влиял только на
 * картинку. Теперь за каждый забег с ним растёт уровень дружбы, а на
 * уровнях 3 / 5 / 10 друг рассказывает свою историю.
 *
 * Хранится отдельным ключом, как боссы и казино: миграцию основного
 * сохранения не трогаем, старые сейвы просто начинают с нуля.
 */



const KEY = "chubgames.friendship";

export interface FriendshipStore {
  /** friendId -> очки дружбы */
  fp: Record<string, number>;
  /** Какие истории уже прочитаны: "friendId:tier" */
  seen: Record<string, number>;
  /** Когда забирали ежечасный сундук, мс */
  chestAt: number;
  /** Сколько сундуков забрано всего — для роста награды */
  chestCount: number;
}

const empty = (): FriendshipStore => ({ fp: {}, seen: {}, chestAt: 0, chestCount: 0 });

export function readFriendship(): FriendshipStore {
  try {
    const raw = localStorage.getItem(KEY);
    if (!raw) return empty();
    return { ...empty(), ...JSON.parse(raw) };
  } catch {
    return empty();
  }
}

export function writeFriendship(s: FriendshipStore) {
  try {
    localStorage.setItem(KEY, JSON.stringify(s));
  } catch {
    /* переполнено — не критично */
  }
}

/* ─────────────────────────  УРОВНИ  ───────────────────────── */

export const FR_MAX = 10;

/** Сколько очков нужно НА уровень l. Растёт мягче мастерства */
export const frNeed = (l: number) => Math.round(4 * Math.pow(l, 1.45));

export function frTotal(l: number) {
  let sum = 0;
  for (let i = 1; i <= l; i++) sum += frNeed(i);
  return sum;
}

export function friendLevel(fp: number): number {
  let lvl = 0;
  for (let l = 1; l <= FR_MAX; l++) {
    if (fp >= frTotal(l)) lvl = l;
    else break;
  }
  return lvl;
}

export function friendProgress(fp: number) {
  const lvl = friendLevel(fp);
  if (lvl >= FR_MAX) return { lvl, have: 0, need: 0, frac: 1 };
  const from = frTotal(lvl);
  const to = frTotal(lvl + 1);
  return { lvl, have: fp - from, need: to - from, frac: (fp - from) / (to - from) };
}

/**
 * Бонус к монетам за дружбу с главным другом: +3% за уровень.
 * Складывается с мастерством, но по отдельной шкале — чтобы выбор
 * друга ощущался, а не терялся в общем множителе.
 */
export const friendBonus = (fp: number) => 1 + friendLevel(fp) * 0.03;

/** Очки за один забег с этим другом */
