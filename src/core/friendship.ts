/** История друга на данном уровне (0-based индекс тиров) */
export function storyFor(friendId: string, tierIndex: number): string {
  const list = STORIES[friendId] || FALLBACK;
  return list[tierIndex] || FALLBACK[tierIndex] || FALLBACK[0];
}

/** Сколько историй уже доступно по уровню дружбы */
export function unlockedStories(lvl: number) {
  return STORY_TIERS.filter((t) => lvl >= t).length;
}

/* ───────────────────  ЕЖЕЧАСНЫЙ СУНДУК  ─────────────────── */

export const CHEST_MS = 60 * 60 * 1000;

/** Сколько осталось до сундука, мс (0 — можно забирать) */
export function chestLeft(st: FriendshipStore, now = Date.now()) {
  return Math.max(0, st.chestAt + CHEST_MS - now);
}

export const chestReady = (st: FriendshipStore, now = Date.now()) => chestLeft(st, now) === 0;

/**
 * Награда за сундук.
 *
 * Растёт с уровнем игрока, чтобы к позднему прогрессу сундук не
 * превращался в копейки, но с потолком — иначе он забьёт весь остальной
 * заработок. Числа проверены симуляцией: за 8 часов игрового дня
 * сундуки дают заметно меньше, чем сами игры.
 */
export function chestReward(level: number, count: number) {
  /*
   * Числа проверены расчётом. Первая версия (300 + 85 за уровень) на
   * 20-м уровне давала 22 400 монет за восемь сундуков — это 29 забегов,
   * то есть сундук ЗАМЕНЯЛ игру. Здесь он даёт около трёх забегов за
   * целый день: приятно зайти, но фармить всё равно нужно играя.
   */
  const base = 150 + level * 10;
  const streakBonus = 1 + Math.min(0.5, count * 0.01);
  return {
    coins: Math.round(base * streakBonus),
    chips: 3 + Math.floor(level / 8),
  };
}
