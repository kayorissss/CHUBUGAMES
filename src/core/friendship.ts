/**
 * ДРУЖБА И ЕЖЕЧАСНЫЙ СУНДУК.
 *
 * Дружба даёт смысл выбору главного друга: раньше он влиял только на
 * картинку. Теперь за каждый забег с ним растёт уровень дружбы, а на
 * уровнях 3 / 5 / 10 друг рассказывает свою историю.
 *
 * Хранится отдельным ключом, как боссы и казино: миграцию основного
 * сохранения не трогаем, старые сейвы просто начинают с нуля.
 */



const KEY = "chubgames.friendship";

export interface FriendshipStore {
  /** friendId -> очки дружбы */
  fp: Record<string, number>;
  /** Какие истории уже прочитаны: "friendId:tier" */
  seen: Record<string, number>;
  /** Когда забирали ежечасный сундук, мс */
  chestAt: number;
  /** Сколько сундуков забрано всего — для роста награды */
  chestCount: number;
}

const empty = (): FriendshipStore => ({ fp: {}, seen: {}, chestAt: 0, chestCount: 0 });

export function readFriendship(): FriendshipStore {
  try {
    const raw = localStorage.getItem(KEY);
    if (!raw) return empty();
    return { ...empty(), ...JSON.parse(raw) };
  } catch {
    return empty();
  }
}

export function writeFriendship(s: FriendshipStore) {
  try {
    localStorage.setItem(KEY, JSON.stringify(s));
  } catch {
    /* переполнено — не критично */
  }
}

