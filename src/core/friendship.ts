export const FR_MAX = 10;

/** Сколько очков нужно НА уровень l. Растёт мягче мастерства */
export const frNeed = (l: number) => Math.round(4 * Math.pow(l, 1.45));

export function frTotal(l: number) {
  let sum = 0;
  for (let i = 1; i <= l; i++) sum += frNeed(i);
  return sum;
}

export function friendLevel(fp: number): number {
  let lvl = 0;
  for (let l = 1; l <= FR_MAX; l++) {
    if (fp >= frTotal(l)) lvl = l;
    else break;
  }
  return lvl;
}

export function friendProgress(fp: number) {
  const lvl = friendLevel(fp);
  if (lvl >= FR_MAX) return { lvl, have: 0, need: 0, frac: 1 };
  const from = frTotal(lvl);
  const to = frTotal(lvl + 1);
  return { lvl, have: fp - from, need: to - from, frac: (fp - from) / (to - from) };
}

/**
 * Бонус к монетам за дружбу с главным другом: +3% за уровень.
 * Складывается с мастерством, но по отдельной шкале — чтобы выбор
 * друга ощущался, а не терялся в общем множителе.
 */
export const friendBonus = (fp: number) => 1 + friendLevel(fp) * 0.03;

/** Очки за один забег с этим другом */
